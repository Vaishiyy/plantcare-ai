export type PlantCondition = 'Healthy' | 'Needs Water' | 'Too Dry' | 'Poor Environment';

export interface SensorReading {
  moisture: number;      // 0 - 100 %
  temperature: number;   // °C
  humidity: number;      // 0 - 100 %
  light: number;         // 0 - 1024 or lux
  condition: PlantCondition;
  timestamp: number;     // epoch ms
  confidence?: number;   // 0.0 - 1.0 (if supplied by model)
  isSynthetic?: boolean; // true if generated by demo mode / simulator
}

export interface Thresholds {
  moistureMin: number;
  moistureMax: number;
  tempMin: number;
  tempMax: number;
  humidityMin: number;
  humidityMax: number;
  lightMin: number;
  lightMax: number;
}

export interface PlantProfile {
  id: string;
  name: string;
  species: string;
  dateAdded: string;
  imageUrl: string;
  careLevel: 'Easy' | 'Moderate' | 'Demanding';
  sunlightRequirement: 'Low Light' | 'Bright Indirect' | 'Direct Sunlight';
  thresholds: Thresholds;
  notes: string;
}

export type AlertSeverity = 'info' | 'warning' | 'critical' | 'success';

export interface AlertItem {
  id: string;
  timestamp: number;
  type: 'moisture_low' | 'moisture_critical' | 'temp_out_of_range' | 'humidity_abnormal' | 'light_abnormal' | 'connection_lost' | 'connection_restored';
  title: string;
  message: string;
  severity: AlertSeverity;
  read: boolean;
  valueRecorded?: number;
  conditionRelated?: PlantCondition;
}

export type ConnectionState = 'disconnected' | 'connecting' | 'connected' | 'error';
export type ConnectionProtocol = 'ble' | 'serial' | 'demo';

export interface AlertPreferences {
  lowMoisture: boolean;
  criticalDry: boolean;
  temperatureExtreme: boolean;
  humidityAbnormal: boolean;
  lightAbnormal: boolean;
  connectionEvents: boolean;
  soundEnabled: boolean;
}

export type ActiveScreen =
  | 'dashboard'
  | 'plant_details'
  | 'live_monitoring'
  | 'ai_analysis'
  | 'history'
  | 'alerts'
  | 'settings';

export type DemoScenario = 'ideal' | 'needs_water' | 'too_dry' | 'poor_env' | 'random_drift';
