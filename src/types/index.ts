export type SuitabilityClass = 'Suitable' | 'Moderate Stress' | 'High Stress';

export type PlantCondition =
  | 'Suitable'
  | 'Moderate Stress'
  | 'High Stress'
  | 'Healthy'
  | 'Needs Water'
  | 'Too Dry'
  | 'Poor Environment';

export interface SensorReading {
  moisture: number;      // 0 - 100 % (soil_humidity_pct)
  temperature: number;   // °C (temperature_c)
  humidity: number;      // 0 - 100 % (air_humidity_pct)
  light: number;         // 0 - 4095 (ldr_on_plant ADC reading)
  condition: PlantCondition;
  suitabilityClass: 'suitable' | 'moderate_stress' | 'high_stress';
  mlClassCode: 0 | 1 | 2; // 0 = High stress, 1 = Moderate stress, 2 = Suitable
  timestamp: number;     // epoch ms
  confidence?: number;   // 0.0 - 1.0 (if supplied by model)
  isSynthetic?: boolean; // true if generated by demo mode / simulator
  datasetRowIndex?: number;
}

export interface Thresholds {
  moistureMin: number;
  moistureMax: number;
  tempMin: number;
  tempMax: number;
  humidityMin: number;
  humidityMax: number;
  lightMin: number;
  lightMax: number;
}

export interface PlantProfile {
  id: string;
  speciesKey: 'aloe_vera' | 'pothos';
  plantCode: 0 | 1; // 0 = Aloe Vera, 1 = Pothos (features[0] for ML model)
  name: string;
  species: string;
  dateAdded: string;
  imageUrl: string;
  careLevel: 'Easy' | 'Moderate' | 'Demanding';
  sunlightRequirement: 'Low Light' | 'Bright Indirect' | 'Direct Sunlight';
  thresholds: Thresholds;
  notes: string;
}

export type AlertSeverity = 'info' | 'warning' | 'critical' | 'success';

export interface AlertItem {
  id: string;
  timestamp: number;
  type:
    | 'moisture_low'
    | 'moisture_critical'
    | 'temp_out_of_range'
    | 'humidity_abnormal'
    | 'light_abnormal'
    | 'connection_lost'
    | 'connection_restored';
  title: string;
  message: string;
  severity: AlertSeverity;
  read: boolean;
  valueRecorded?: number;
  conditionRelated?: PlantCondition;
}

export type ConnectionState = 'disconnected' | 'connecting' | 'connected' | 'error';
export type ConnectionProtocol = 'ble' | 'serial' | 'demo';

export interface AlertPreferences {
  lowMoisture: boolean;
  criticalDry: boolean;
  temperatureExtreme: boolean;
  humidityAbnormal: boolean;
  lightAbnormal: boolean;
  connectionEvents: boolean;
  soundEnabled: boolean;
}

